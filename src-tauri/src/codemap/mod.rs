/// What the viewer draws a file as.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub(crate) enum FileKind {
    Ts,
    /// A `.d.ts` declaration file.
    Dts,
    /// TSX or JSX.
    Tsx,
    Js,
    Py,
    Sql,
    Sh,
    Css,
    Svg,
    Json,
    Yml,
    Image,
    Other,
}

const CODE_EXTENSIONS: [&str; 40] = [
    "ts", "tsx", "js", "jsx", "mjs", "cjs", "mts", "cts", "py", "sql", "sh", "bash", "css", "scss",
    "less", "svg", "json", "yaml", "yml", "toml", "go", "rs", "java", "kt", "kts", "rb", "php",
    "swift", "c", "cc", "cpp", "h", "hpp", "cs", "vue", "svelte", "graphql", "gql", "prisma",
    "proto",
];
const IMAGE_EXTENSIONS: [&str; 5] = ["png", "jpg", "jpeg", "webp", "gif"];
const SKIPPED_FOLDERS: [&str; 8] = [
    "node_modules",
    "dist",
    "build",
    ".next",
    ".turbo",
    "coverage",
    "vendor",
    "__pycache__",
];
const LOCKFILES: [&str; 7] = [
    "pnpm-lock.yaml",
    "package-lock.json",
    "yarn.lock",
    "bun.lockb",
    "Cargo.lock",
    "poetry.lock",
    "go.sum",
];
/// Images up to this size are embedded, since the page can't load them from disk.
const MAX_EMBEDDED_IMAGE_BYTES: u64 = 200 * 1024;
/// How far into a file a generated-code banner is looked for.
const BANNER_LINES: usize = 30;

static GENERATED_BANNER: LazyLock<Regex> = LazyLock::new(|| {
    Regex::new(
        r"(?i)@generated|DO NOT EDIT|do not edit (this|manually)|auto-?generated file|this file (is|was) (auto-?)?generated|code generated by|generated by:|generated by (graphql-codegen|pgtyped|prisma|protoc|openapi|orval|zod2pydantic)|types generated for queries found in",
    )
    .expect("valid regex")
});
static COMMENT_LINE: LazyLock<Regex> =
    LazyLock::new(|| Regex::new(r"^\s*(//|/\*|\*|#|<!--|--)").expect("valid regex"));
static SVG_VIEW_BOX: LazyLock<Regex> = LazyLock::new(|| {
    Regex::new(r#"viewBox=["']\s*[-\d.]+[ ,]+[-\d.]+[ ,]+([\d.]+)[ ,]+([\d.]+)"#)
        .expect("valid regex")
});
static SVG_WIDTH: LazyLock<Regex> =
    LazyLock::new(|| Regex::new(r#"<svg[^>]*\swidth=["']([\d.]+)"#).expect("valid regex"));
static SVG_HEIGHT: LazyLock<Regex> =
    LazyLock::new(|| Regex::new(r#"<svg[^>]*\sheight=["']([\d.]+)"#).expect("valid regex"));

fn extension(path: &str) -> Option<String> {
    let name = path.rsplit('/').next()?;
    let (_, extension) = name.rsplit_once('.')?;
    Some(extension.to_ascii_lowercase())
}

impl FileKind {
    fn of(path: &str) -> Self {
        match extension(path).as_deref() {
            Some("png" | "jpg" | "jpeg" | "webp" | "gif") => Self::Image,
            Some("ts" | "mts" | "cts") if path.ends_with(".d.ts") => Self::Dts,
            Some("ts" | "mts" | "cts") => Self::Ts,
            Some("tsx" | "jsx") => Self::Tsx,
            Some("js" | "mjs" | "cjs") => Self::Js,
            Some("css" | "scss" | "less") => Self::Css,
            Some("yml" | "yaml") => Self::Yml,
            Some("sh" | "bash") => Self::Sh,
            Some("py") => Self::Py,
            Some("sql") => Self::Sql,
            Some("svg") => Self::Svg,
            Some("json") => Self::Json,
            _ => Self::Other,
        }
    }

    fn viewer_name(self) -> &'static str {
        match self {
            Self::Ts => "ts",
            Self::Dts => "dts",
            Self::Tsx => "tsx",
            Self::Js => "js",
            Self::Py => "py",
            Self::Sql => "sql",
            Self::Sh => "sh",
            Self::Css => "css",
            Self::Svg => "svg",
            Self::Json => "json",
            Self::Yml => "yml",
            Self::Image => "img",
            Self::Other => "code",
        }
    }
}

/// Source and images worth drawing, without dependencies, build output, lockfiles or secrets.
fn is_mapped(path: &str) -> bool {
    let Some(extension) = extension(path) else {
        return false;
    };
    if !CODE_EXTENSIONS.contains(&extension.as_str())
        && !IMAGE_EXTENSIONS.contains(&extension.as_str())
    {
        return false;
    }
    let segments: Vec<&str> = path.split('/').collect();
    let (name, folders) = segments.split_last().expect("split yields one segment");
    let skipped = folders
        .iter()
        .any(|folder| SKIPPED_FOLDERS.contains(folder))
        || segments.iter().any(|segment| segment.starts_with(".env"))
        || LOCKFILES.contains(name)
        || path.ends_with(".min.js")
        || path.ends_with(".min.css");
    !skipped
}

/// A ref as the viewer's header shows it.
#[derive(Debug, Clone, Serialize)]
pub struct RefInfo {
    /// "worktree" for the working tree.
    #[serde(rename = "ref")]
    reference: String,
    #[serde(skip_serializing_if = "Option::is_none")]
    hash: Option<String>,
    label: String,
    short: String,
    date: String,
    subject: String,
}

#[derive(Debug, Serialize)]
pub struct Refs {
    head: RefInfo,
    base: RefInfo,
}

/// A file on the map, in the viewer's field names.
#[derive(Debug, Serialize)]
pub struct Node {
    #[serde(rename = "p")]
    path: String,
    #[serde(rename = "k")]
    kind: &'static str,
    #[serde(rename = "b")]
    bytes: u64,
    #[serde(rename = "l")]
    lines: usize,
    #[serde(rename = "g", skip_serializing_if = "std::ops::Not::not")]
    generated: bool,
    #[serde(rename = "iw", skip_serializing_if = "Option::is_none")]
    image_width: Option<f64>,
    #[serde(rename = "ih", skip_serializing_if = "Option::is_none")]
    image_height: Option<f64>,
    /// A data URL, for images small enough to embed.
    #[serde(rename = "u", skip_serializing_if = "Option::is_none")]
    image_url: Option<String>,
    /// External packages it imports.
    #[serde(rename = "x")]
    packages: Vec<String>,
    #[serde(rename = "o")]
    shape_offset: usize,
    #[serde(rename = "r")]
    shape_rows: usize,
    #[serde(rename = "s")]
    lines_per_row: f64,
    /// A, M, R or D; absent when unchanged.
    #[serde(rename = "st", skip_serializing_if = "Option::is_none")]
    status: Option<&'static str>,
    #[serde(rename = "op", skip_serializing_if = "Option::is_none")]
    old_path: Option<String>,
    #[serde(rename = "hk", skip_serializing_if = "Vec::is_empty")]
    hunks: Vec<Hunk>,
    #[serde(rename = "ad", skip_serializing_if = "Option::is_none")]
    lines_added: Option<usize>,
    #[serde(rename = "dl", skip_serializing_if = "Option::is_none")]
    lines_removed: Option<usize>,
}

/// Whether a link exists on both sides of the comparison or only one.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
#[repr(u8)]
enum LinkChange {
    Kept = 0,
    Added = 1,
    Removed = 2,
}

/// An import between two nodes, which the viewer reads as `[from, to, kind, via, change]`.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct GraphLink {
    from: usize,
    to: usize,
    kind: LinkKind,
    via: Option<usize>,
    change: LinkChange,
}

impl Serialize for GraphLink {
    fn serialize<S: Serializer>(&self, serializer: S) -> Result<S::Ok, S::Error> {
        let mut tuple = serializer.serialize_tuple(5)?;
        tuple.serialize_element(&self.from)?;
        tuple.serialize_element(&self.to)?;
        tuple.serialize_element(&(self.kind as u8))?;
        tuple.serialize_element(&self.via.map_or(-1, |via| via as i64))?;
        tuple.serialize_element(&(self.change as u8))?;
        tuple.end()
    }
}

#[derive(Debug, Serialize)]
pub struct Graph {
    repo: String,
    /// The head's short hash, date and subject.
    commit: [String; 3],
    refs: Refs,
    diff: bool,
    containers: Vec<String>,
    nodes: Vec<Node>,
    /// Each import to the module it names.
    edges: Vec<GraphLink>,
    /// Each import to the files defining what it imports, past barrels.
    tedges: Vec<GraphLink>,
    /// External packages and how often they're imported.
    ext: Vec<(String, usize)>,
}

#[derive(Debug, Serialize)]
pub struct Codemap {
    pub graph: Graph,
    /// Every file's code shape in one buffer, gzipped then base64-encoded.
    pub shapes: String,
    /// SVG sources by path, which the viewer draws as pictures.
    pub svgs: BTreeMap<String, String>,
}

struct ScannedFile {
    path: String,
    kind: FileKind,
    bytes: u64,
    text: String,
    lines: usize,
    generated: bool,
    image_size: Option<(f64, f64)>,
    image_url: Option<String>,
    packages: Vec<String>,
}

/// An import by path, so links from two snapshots can be matched.
struct PathLink {
    from: String,
    to: String,
    kind: LinkKind,
    via: Option<String>,
}

struct Scan {
    files: Vec<ScannedFile>,
    index: HashMap<String, usize>,
    links: Vec<PathLink>,
    through_links: Vec<PathLink>,
    packages: Vec<(String, usize)>,
    containers: Vec<String>,
}

fn image_mime(path: &str) -> &'static str {
    match extension(path).as_deref() {
        Some("png") => "image/png",
        Some("gif") => "image/gif",
        Some("webp") => "image/webp",
        _ => "image/jpeg",
    }
}

fn line_count(text: &str) -> usize {
    let parts = text.split('\n').count();
    if text.is_empty() || text.ends_with('\n') {
        parts - 1
    } else {
        parts
    }
}

fn is_generated(text: &str) -> bool {
    let banner: Vec<&str> = text
        .lines()
        .take(BANNER_LINES)
        .filter(|line| COMMENT_LINE.is_match(line))
        .collect();
    GENERATED_BANNER.is_match(&banner.join("\n"))
}

fn svg_size(text: &str) -> Option<(f64, f64)> {
    let number = |captures: Option<regex::Captures>| -> Option<f64> { captures?[1].parse().ok() };
    if let Some(view_box) = SVG_VIEW_BOX.captures(text) {
        return Some((view_box[1].parse().ok()?, view_box[2].parse().ok()?));
    }
    Some((
        number(SVG_WIDTH.captures(text))?,
        number(SVG_HEIGHT.captures(text))?,
    ))
}

fn scan_file(file: SnapshotFile) -> ScannedFile {
    let kind = FileKind::of(&file.path);
    let mut scanned = ScannedFile {
        kind,
        bytes: file.size,
        text: String::new(),
        lines: 0,
        generated: false,
        image_size: None,
        image_url: None,
        packages: Vec::new(),
        path: file.path,
    };
    if kind == FileKind::Image {
        if let Some(contents) = &file.contents {
            scanned.image_size = image_size::image_size(contents)
                .map(|(width, height)| (f64::from(width), f64::from(height)));
            if file.size <= MAX_EMBEDDED_IMAGE_BYTES {
                let encoded = base64::engine::general_purpose::STANDARD.encode(contents);
                scanned.image_url = Some(format!(
                    "data:{};base64,{encoded}",
                    image_mime(&scanned.path)
                ));
            }
        }
        return scanned;
    }
    scanned.text = file
        .contents
        .map(|contents| String::from_utf8_lossy(&contents).into_owned())
        .unwrap_or_default();
    scanned.lines = line_count(&scanned.text);
    scanned.generated = is_generated(&scanned.text);
    if kind == FileKind::Svg {
        scanned.image_size = svg_size(&scanned.text);
    }
    scanned
}

fn scan(files: Vec<SnapshotFile>) -> Scan {
    let mut files: Vec<ScannedFile> = files.into_iter().map(scan_file).collect();
    let paths: Vec<String> = files.iter().map(|file| file.path.clone()).collect();
    let index: HashMap<String, usize> = paths
        .iter()
        .enumerate()
        .map(|(at, path)| (path.clone(), at))
        .collect();
    let resolver = Resolver::new(&paths, |path| {
        index.get(path).map(|&at| files[at].text.as_str())
    });
    let sources: Vec<SourceFile> = files
        .iter()
        .map(|file| SourceFile {
            path: &file.path,
            kind: file.kind,
            text: &file.text,
        })
        .collect();
    let graph = analyze(&sources, &resolver);
    drop(sources);
    for (file, packages) in files.iter_mut().zip(graph.file_packages) {
        file.packages = packages;
    }
    let by_path = |links: Vec<imports::Link>| -> Vec<PathLink> {
        links
            .into_iter()
            .map(|link| PathLink {
                from: paths[link.from].clone(),
                to: paths[link.to].clone(),
                kind: link.kind,
                via: link.via.map(|via| paths[via].clone()),
            })
            .collect()
    };
    Scan {
        links: by_path(graph.links),
        through_links: by_path(graph.through_links),
        packages: graph.packages,
        containers: resolver.containers,
        files,
        index,
    }
}

/// The union of both sides' links, each marked kept, added or removed.
fn merge_links(
    head: &[PathLink],
    base: &[PathLink],
    renamed_from: &HashMap<String, String>,
    index: &HashMap<&str, usize>,
) -> Vec<GraphLink> {
    let rename = |path: &str| -> String {
        renamed_from
            .get(path)
            .cloned()
            .unwrap_or_else(|| path.to_owned())
    };
    let mut position: HashMap<(String, String), usize> = HashMap::new();
    let mut merged: Vec<(PathLink, LinkChange)> = Vec::new();
    for link in head {
        let key = (link.from.clone(), link.to.clone());
        if position.contains_key(&key) {
            continue;
        }
        position.insert(key, merged.len());
        merged.push((
            PathLink {
                from: link.from.clone(),
                to: link.to.clone(),
                kind: link.kind,
                via: link.via.clone(),
            },
            LinkChange::Added,
        ));
    }
    for link in base {
        let key = (rename(&link.from), rename(&link.to));
        match position.get(&key) {
            Some(&at) => merged[at].1 = LinkChange::Kept,
            None => {
                position.insert(key.clone(), merged.len());
                merged.push((
                    PathLink {
                        from: key.0,
                        to: key.1,
                        kind: link.kind,
                        via: link.via.as_deref().map(rename),
                    },
                    LinkChange::Removed,
                ));
            }
        }
    }
    merged
        .into_iter()
        .filter_map(|(link, change)| {
            Some(GraphLink {
                from: *index.get(link.from.as_str())?,
                to: *index.get(link.to.as_str())?,
                kind: link.kind,
                via: link.via.and_then(|via| index.get(via.as_str()).copied()),
                change,
            })
        })
        .collect()
}

fn describe_commit(
    root: &Path,
    rev: &str,
    reference: &str,
    label: &str,
) -> Result<RefInfo, GitError> {
    let line = run_git_text(root, &["log", "-1", "--format=%H%x09%h%x09%cs%x09%s", rev])?;
    let mut fields = line.splitn(4, '\t').map(str::to_owned);
    let mut next = || fields.next().unwrap_or_default();
    Ok(RefInfo {
        reference: reference.to_owned(),
        hash: Some(next()),
        short: next(),
        date: next(),
        subject: next(),
        label: label.to_owned(),
    })
}

fn describe_worktree(root: &Path, label: &str) -> Result<RefInfo, GitError> {
    let head = describe_commit(root, "HEAD", "HEAD", label)?;
    Ok(RefInfo {
        reference: "worktree".into(),
        hash: None,
        subject: format!("uncommitted changes on top of {}", head.short),
        date: String::new(),
        ..head
    })
}

fn gzip(bytes: &[u8]) -> Result<Vec<u8>, GitError> {
    let mut encoder = GzEncoder::new(Vec::new(), Compression::default());
    encoder
        .write_all(bytes)
        .and_then(|()| encoder.finish())
        .map_err(|err| GitError::Command(format!("could not compress the code shapes: {err}")))
}

fn status_code(change: Option<&Change>, in_head: bool, in_base: bool) -> Option<&'static str> {
    if !in_head {
        return Some("D");
    }
    match change {
        Some(Change::Renamed { .. }) => Some("R"),
        Some(Change::Added) => Some("A"),
        _ if !in_base => Some("A"),
        Some(Change::Modified) => Some("M"),
        _ => None,
    }
}

/// Maps the comparison from `merge_base` to `compare`, or to the working tree when `compare` is `None`.
pub fn build_codemap(
    root: &Path,
    merge_base: &str,
    compare: Option<&str>,
    base_label: &str,
    compare_label: &str,
) -> Result<Codemap, GitError> {
    let head_ref = match compare {
        Some(compare) => describe_commit(root, compare, compare_label, compare_label)?,
        None => describe_worktree(root, compare_label)?,
    };
    let base_ref = describe_commit(root, merge_base, base_label, base_label)?;

    let head = scan(match compare {
        Some(compare) => read_commit(root, compare, is_mapped)?,
        None => read_worktree(root, is_mapped)?,
    });
    let base = scan(read_commit(root, merge_base, is_mapped)?);
    let changes = read_changes(root, merge_base, compare)?;

    let mut renamed_from = HashMap::new();
    for (path, change) in &changes.status {
        if let Change::Renamed { from } = change {
            renamed_from.insert(from.clone(), path.clone());
        }
    }
    let deleted = base.files.iter().filter(|file| {
        !head.index.contains_key(&file.path) && !renamed_from.contains_key(&file.path)
    });
    let shown: Vec<(&ScannedFile, bool)> = head
        .files
        .iter()
        .map(|file| (file, true))
        .chain(deleted.map(|file| (file, false)))
        .collect();
    let index: HashMap<&str, usize> = shown
        .iter()
        .enumerate()
        .map(|(at, (file, _))| (file.path.as_str(), at))
        .collect();
    let base_paths: HashSet<&str> = base.files.iter().map(|file| file.path.as_str()).collect();

    let mut shape_bytes = Vec::new();
    let mut svgs = BTreeMap::new();
    let mut nodes = Vec::with_capacity(shown.len());
    for (file, in_head) in &shown {
        let (shape_offset, shape_rows, lines_per_row) = if file.kind == FileKind::Image {
            (shape_bytes.len(), 0, 1.0)
        } else {
            if file.kind == FileKind::Svg {
                svgs.insert(file.path.clone(), file.text.clone());
            }
            let span = encode_shape(&file.text, file.kind, file.lines, &mut shape_bytes);
            (span.offset, span.rows, span.lines_per_row)
        };
        let change = changes.status.get(&file.path);
        let status = status_code(change, *in_head, base_paths.contains(file.path.as_str()));
        let hunks = if status.is_some() {
            changes.hunks.get(&file.path).cloned().unwrap_or_default()
        } else {
            Vec::new()
        };
        let lines_in_hunks = |side: usize| hunks.iter().map(|hunk| hunk[side] as usize).sum();
        let lines_added = status.map(|status| {
            if status == "A" && hunks.is_empty() {
                file.lines
            } else {
                lines_in_hunks(1)
            }
        });
        let lines_removed = status.map(|status| {
            if status == "D" {
                file.lines
            } else {
                lines_in_hunks(3)
            }
        });
        nodes.push(Node {
            path: file.path.clone(),
            kind: file.kind.viewer_name(),
            bytes: file.bytes,
            lines: file.lines,
            generated: file.generated,
            image_width: file.image_size.map(|(width, _)| width),
            image_height: file.image_size.map(|(_, height)| height),
            image_url: file.image_url.clone(),
            packages: file.packages.clone(),
            shape_offset,
            shape_rows,
            lines_per_row,
            status,
            old_path: match change {
                Some(Change::Renamed { from }) if status == Some("R") => Some(from.clone()),
                _ => None,
            },
            hunks,
            lines_added,
            lines_removed,
        });
    }

    let repo = root
        .file_name()
        .map(|name| name.to_string_lossy().into_owned())
        .unwrap_or_default();
    let graph = Graph {
        repo,
        commit: [
            head_ref.short.clone(),
            head_ref.date.clone(),
            head_ref.subject.clone(),
        ],
        refs: Refs {
            head: head_ref,
            base: base_ref,
        },
        diff: true,
        containers: head.containers.clone(),
        edges: merge_links(&head.links, &base.links, &renamed_from, &index),
        tedges: merge_links(
            &head.through_links,
            &base.through_links,
            &renamed_from,
            &index,
        ),
        ext: head.packages.clone(),
        nodes,
    };
    Ok(Codemap {
        graph,
        shapes: base64::engine::general_purpose::STANDARD.encode(gzip(&shape_bytes)?),
        svgs,
    })
}

